  it("publishes clear partner, consent, data-transfer, and emergency boundaries in Terms and Privacy", () => {
    const terms = projectFile("client/src/pages/Terms.tsx");
    const privacy = projectFile("client/src/pages/Privacy.tsx");
    expect(terms).toContain("Independent providers and telehealth partners are responsible");
    expect(terms).toContain("will identify the recipient and data categories and request separate authorization");
    expect(terms).toContain("Call 911 or your local emergency number");
    expect(privacy).toContain("will not transmit your lab results, uploaded documents, symptoms, diagnoses, medications, AI conversations, or biomarker history");
    expect(privacy).toContain("will not place health information in referral URLs, advertising pixels, or general-purpose analytics");
  });

  it("includes attorney-review legal language and an implementation-ready BAA checklist", () => {
    const legalDraft = projectFile("LICENSED_CARE_CONNECTIONS_LEGAL_DRAFT.md");
    const checklist = projectFile("LICENSED_CARE_CONNECTIONS_TECHNICAL_BAA_CHECKLIST.md");
    expect(legalDraft).toContain("Draft — attorney review required before publication or launch");
    expect(legalDraft).toContain("No Provider-Patient Relationship With The Patient’s Compass");
    expect(checklist).toContain("no-PHI-by-default referral handoff");
    expect(checklist).toContain("BAA Clause Checklist");
    expect(checklist).toContain("Go-Live Gates");
  });

